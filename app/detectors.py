# 위 줄(%%writefile)은 이 셀의 내용을 실행하지 않고 app/detectors.py 라는 파일로 저장하라는 주피터 명령이다
"""
규칙 기반 부품: 타임스탬프 판별, 정규식 탐지, 탐지 조각 합치기.
모델 없이 동작하므로 서버를 띄우지 않고도 단독으로 시험할 수 있다.
"""
# re(정규식 모듈)를 가져온다 — 글자 '패턴'으로 개인정보와 타임스탬프를 찾으려고
import re


# ── 1. 타임스탬프 판별 ───────────────────────
# 타임스탬프 패턴을 미리 해석해 둔다 (re.compile = 한 번 해석해 두고 여러 줄에 재사용)
#   ^ ... $        : 줄 '전체'가 이 모양일 때만 일치 (발언 중간의 '2:30'은 걸리지 않음)
#   \d{1,2}:\d{2}  : 숫자 1~2개, 콜론, 숫자 2개 (00:07)
#   (:\d{2})?      : ':숫자 2개'가 있어도 없어도 됨 (1시간 넘는 녹음의 01:02:15)
TIMESTAMP = re.compile(r"^\d{1,2}:\d{2}(:\d{2})?$")


# 한 줄을 받아 타임스탬프 줄이면 True, 아니면 False를 돌려주는 함수
def is_timestamp(line: str) -> bool:
    # line.strip() = 앞뒤 공백 제거 / .match = 줄 처음부터 패턴과 비교 / bool() = 결과를 True·False로 바꾼다
    return bool(TIMESTAMP.match(line.strip()))


# ── 2. 정규식 탐지 규칙 ──────────────────────
# 음성 변환 앱이 숫자를 한글로 받아 적을 때 쓰는 글자들 (공=0, 영=0, 일=1 ... 구=9)
KOR_DIGITS = "공영일이삼사오육칠팔구"

# (유형 이름, 패턴) 목록. 나열 순서 = 우선순위 (앞일수록 겹칠 때 라벨을 차지한다)
# 정규식 공통 기호:
#   (?<!\d) : '바로 앞 글자가 숫자가 아닐 것' — 더 긴 숫자의 중간부터 잘못 잡지 않게
#   (?!\d)  : '바로 뒤 글자가 숫자가 아닐 것' — 더 긴 숫자의 앞부분만 잘못 잡지 않게
#   \d{n}   : 숫자 정확히 n개 / \d{a,b} : 숫자 a~b개 / [-\s]? : 하이픈이나 공백이 있어도 없어도 됨
REGEX_RULES = [
    # 주민등록번호: 6자리 - 7자리. 뒷자리 첫 글자는 성별·세기 숫자라 1~8만 허용
    ("주민등록번호", re.compile(r"(?<!\d)\d{6}\s?-\s?[1-8]\d{6}(?!\d)")),
    # 카드번호: 4자리씩 네 묶음, 사이에 하이픈이나 공백
    ("카드번호", re.compile(r"(?<!\d)\d{4}[-\s]\d{4}[-\s]\d{4}[-\s]\d{4}(?!\d)")),
    # 전화번호: 0으로 시작(010, 02 등) + 3~4자리 + 4자리, 구분자는 하이픈·공백·점 또는 없음
    ("전화번호", re.compile(r"(?<!\d)0\d{1,2}[-\s.]?\d{3,4}[-\s.]?\d{4}(?!\d)")),
    # 계좌번호: 숫자 묶음 세 개를 하이픈으로 연결. 마지막 묶음을 4자리 이상으로 둬서 2026-11-05 같은 날짜는 안 걸리게
    #   (주의: 010-3847-2915 같은 휴대전화도 이 모양에 맞는다 — D41 실습에서 본 바로 그 오탐.
    #    전화번호 규칙이 더 앞에 있으므로, 둘이 겹치면 merge_spans가 '전화번호' 라벨을 남긴다)
    ("계좌번호", re.compile(r"(?<!\d)\d{3,6}-\d{2,6}-\d{4,8}(?!\d)")),
    # 이메일: 영문·숫자·기호 + @ + 도메인 + . + 영문 2글자 이상 (.co.kr처럼 점이 여러 번이어도 됨)
    ("이메일", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")),
    # 한글로 받아 적힌 휴대전화: '공일공/영일영' 으로 시작 + 한글 숫자 7~8개 (사이 공백 허용)
    #   rf"..." = 정규식용 글자(r)이면서 {KOR_DIGITS} 자리에 변수 값을 끼워 넣는 글자(f)
    #   {{7,8}} = f-문자열 안에서 중괄호를 글자 그대로 쓰려면 두 번 겹쳐 써야 해서 (결과는 {7,8})
    #   '공일공'으로 시작하는 경우만 잡는 이유: '이삼사' 같은 글자는 일반 단어에도 나와서 오탐이 많아지기 때문
    ("전화번호", re.compile(rf"[공영]일[공영](?:\s*[{KOR_DIGITS}]){{7,8}}")),
    # 기관명: 한글·영문·숫자 1글자 이상 + 기관을 뜻하는 끝말 (한빛고등학교, 한결전자, 한빛학원)
    #   끝말 앞에 반드시 글자가 붙어 있어야 해서, '학원 끝나는'처럼 띄어 쓴 일반 단어는 걸리지 않는다
    ("기관", re.compile(r"[가-힣A-Za-z0-9]+(?:초등학교|중학교|고등학교|대학교|대학원|학원|병원|의원|센터|전자|주식회사)")),
]

# 모델 탐지의 우선순위 값 — 정규식(0~6)보다 항상 뒤로 밀리도록 큰 수로 둔다
MODEL_PRIORITY = 100

# 모델이 붙이는 영어 라벨 → 화면에 보일 한국어 유형 이름 대응표
MODEL_LABEL_MAP = {
    "private_person": "이름",
    "private_address": "주소",
    "private_phone": "전화번호",
    "private_email": "이메일",
    "private_date": "날짜",
    "account_number": "계좌번호",
}


# 모델 라벨을 한국어 유형으로 바꾸는 함수
def model_label(raw_label: str) -> str:
    # .get(열쇠, 기본값) = 표에 있으면 그 값을, 없으면 기본값을 돌려준다
    # 표에 없는 라벨도 '기타개인정보'로 가린다 — 모르는 것은 안전한 쪽으로(fail-closed). 표에 없다고 그냥 통과시키면 유출된다
    return MODEL_LABEL_MAP.get(raw_label, "기타개인정보")


# 한 줄에서 정규식 규칙을 전부 돌려 탐지 목록을 돌려주는 함수
def find_regex(line: str) -> list[dict]:
    # 탐지 결과를 담을 빈 리스트
    spans = []
    # enumerate = 목록을 꺼내면서 순번(0, 1, 2...)도 함께 준다 → 그 순번을 우선순위로 쓴다
    for priority, (label, pattern) in enumerate(REGEX_RULES):
        # finditer = 한 줄 안에서 패턴에 맞는 곳을 '모두' 하나씩 찾아 준다 (search는 첫 번째 하나만)
        for m in pattern.finditer(line):
            # 찾은 곳 하나를 사전으로 기록한다. start/end = 원문에서의 시작·끝 위치(끝은 그 글자 '바로 다음' 위치)
            spans.append({
                "start": m.start(),
                "end": m.end(),
                "type": label,
                "source": "regex",
                "priority": priority,
            })
    # 이 줄에서 찾은 전부를 돌려준다
    return spans


# ── 3. 조각 합치기 ───────────────────────────
# 정규식 결과와 모델 결과를 한데 모은 목록을 받아, 조각을 합치고 겹침을 정리한 목록을 돌려주는 함수
def merge_spans(line: str, spans: list[dict]) -> list[dict]:
    # 시작 위치 순으로 정렬한다. 시작이 같으면 우선순위 높은(숫자 작은) 것이 먼저 오게
    #   key=lambda s: (...) = '각 항목에서 이 값을 꺼내 그 값으로 정렬하라'는 짧은 함수
    ordered = sorted(spans, key=lambda s: (s["start"], s["priority"]))
    # 합친 결과를 담을 빈 리스트
    merged = []
    # 정렬된 탐지를 하나씩 꺼낸다
    for s in ordered:
        # 이미 담긴 것이 하나라도 있으면, 바로 앞(마지막)에 담긴 것과 비교한다
        if merged:
            # 마지막에 담긴 탐지
            last = merged[-1]
            # 겹침: 지금 것의 시작이 앞 것의 끝보다 앞이면 두 범위가 포개진 것
            overlap = s["start"] < last["end"]
            # 앞 것의 끝과 지금 것의 시작 사이 글자 (붙어 있으면 빈 글자 "")
            gap = line[last["end"]:s["start"]]
            # 같은 유형 + 겹치지 않음 + 사이가 공백 1칸 이하 → 같은 덩어리의 조각으로 본다 ('박지'+'영', '서울시'+' '+'노원')
            touching_same = (
                s["type"] == last["type"]
                and s["start"] >= last["end"]
                and len(gap) <= 1
                and gap.strip() == ""
            )
            # 둘 중 하나라도 해당하면 새로 담지 않고 앞 것에 합친다
            if overlap or touching_same:
                # 끝 위치를 둘 중 더 뒤쪽으로 넓힌다 — 합집합. 애매하면 더 많이 가리는 쪽(fail-closed)
                last["end"] = max(last["end"], s["end"])
                # 지금 것의 우선순위가 더 높으면(숫자가 작으면) 라벨·출처·우선순위를 지금 것으로 바꾼다
                #   예: 모델이 '계좌번호'라 한 090315-4123456 → 정규식의 '주민등록번호'가 이긴다
                if s["priority"] < last["priority"]:
                    last["type"] = s["type"]
                    last["source"] = s["source"]
                    last["priority"] = s["priority"]
                # 합쳤으니 새로 담지 않고 다음 탐지로 넘어간다
                continue
        # 합칠 대상이 아니면 새 덩어리로 담는다
        #   dict(s) = 복사본을 담는다 — 위에서 last["end"]를 고칠 때 원래 목록의 사전까지 바뀌지 않게
        merged.append(dict(s))
    # 정리된 목록을 돌려준다
    return merged
